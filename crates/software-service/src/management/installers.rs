//! Local file preparation composes the existing Content, Resource and Software owners.
use super::{
    Error, Failure,
    catalog::Access,
    content::*,
    transaction::{self, TransactionOwner},
};
use rss_mdm_audit_integration::RequestAudit;
use rss_mdm_authorization_service::{Permission, context::AuthorizedPrincipal};
use rss_mdm_resource as r;
use serde::{Deserialize, Serialize};
use serde_json::{Value, json};
use uuid::Uuid;
#[derive(Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct Save {
    pub operation_id: Uuid,
    pub package_id: Uuid,
    pub version: Option<String>,
    pub target: rss_mdm_agent_wire::enroll::configuration::Target,
    /// Complete existing execution definition; the uploaded artifact key is `package`.
    pub behavior: Option<r::SoftwareBehavior>,
}
fn actor(p: &AuthorizedPrincipal) -> String {
    format!("{}:{}", p.instance_id(), p.principal_id())
}
async fn authorize<C: ManagementContentPort>(
    app: &Access<C>,
    p: &AuthorizedPrincipal,
) -> Result<(), Error> {
    p.manage(Permission::SoftwareWrite)?;
    p.manage(Permission::ResourceWrite)?;
    if p.tenant_id() != app.tenant.to_string() {
        return Err(Error::Forbidden);
    }
    transaction::inspect(
        &app.runtime,
        app.tenant,
        p,
        |p, tx| {
            Box::pin(async move {
                let snapshot = transaction::current(tx, p).await?;
                snapshot.require(p, Permission::SoftwareWrite, None)?;
                snapshot.require(p, Permission::ResourceWrite, None)?;
                p.check_live()?;
                Ok(())
            })
        },
        TransactionOwner::SoftwareCatalog,
    )
    .await
}
/// File coordinates are generated by software preparation; users supply no Resource/variant/manifest.
pub async fn begin<C: ManagementContentPort>(
    app: &Access<C>,
    p: &AuthorizedPrincipal,
    input: &PrepareUpload,
) -> Result<Value, Error> {
    authorize(app, p).await?;
    if input.operation_id.is_nil()
        || input.filename.is_empty()
        || input.filename.len() > 255
        || input
            .filename
            .chars()
            .any(|c| c.is_control() || matches!(c, '/' | '\\'))
        || !matches!(
            input
                .filename
                .rsplit('.')
                .next()
                .unwrap_or("")
                .to_ascii_lowercase()
                .as_str(),
            "exe" | "msi" | "msix" | "pkg"
        )
    {
        return Err(Error::Malformed);
    }
    app.content
        .as_ref()
        .ok_or(Error::Unsupported)?
        .prepare_upload(
            input,
            &input.operation_id.to_string(),
            input.operation_id,
            &actor(p),
        )
        .await
}
pub async fn inspect<C: ManagementContentPort>(
    app: &Access<C>,
    p: &AuthorizedPrincipal,
    id: Uuid,
) -> Result<Value, Error> {
    authorize(app, p).await?;
    let file = app
        .content
        .as_ref()
        .ok_or(Error::Unsupported)?
        .inspect_upload(id, &actor(p), &id.to_string())
        .await?;
    Ok(
        json!({"packageId":id,"filename":file.filename,"length":file.artifact.length,"sha256":file.artifact.sha256,"facts":file.facts}),
    )
}
/// Save the original operation; replay precedes upload expiry and all external I/O.
pub async fn save<C: ManagementContentPort>(
    app: &Access<C>,
    p: &AuthorizedPrincipal,
    audit: &RequestAudit,
    input: &Save,
) -> Result<Value, Error> {
    authorize(app, p).await?;
    p.bind_audit(audit)?;
    if input.operation_id.is_nil() || input.package_id.is_nil() {
        return Err(Error::Malformed);
    }
    audit.operation(input.operation_id, "software_installer_save");
    audit.require_request_settlement();
    let hash = crate::catalog::fingerprint(&(
        "installer-save-v1",
        p.instance_id(),
        p.principal_id(),
        input,
    ))
    .map_err(|_| Error::Malformed)?;
    let old = transaction::inspect(
        &app.runtime,
        app.tenant,
        (&app, input.operation_id, &hash),
        |ctx, tx| {
            Box::pin(async move {
                let (app, operation, hash) = *ctx;
                app.catalog.reader().lock_in(tx).await?;
                Ok(app
                    .catalog
                    .reader()
                    .operation_receipt_in(tx, operation, hash)
                    .await?)
            })
        },
        TransactionOwner::SoftwareCatalog,
    )
    .await?;
    if let Some(value) = old {
        return transaction::run(
            &app.audit,
            &app.runtime,
            app.tenant,
            audit,
            (app, p, audit, input, hash, value),
            |ctx, tx| {
                Box::pin(async move {
                    let (app, p, audit, input, hash, value) = ctx;
                    let snapshot = transaction::current(tx, p).await?;
                    snapshot.require(p, Permission::SoftwareWrite, None)?;
                    snapshot.require(p, Permission::ResourceWrite, None)?;
                    let fact = rss_mdm_audit_integration::Fact::business(
                        audit,
                        &format!("software:{}", input.operation_id),
                        hash,
                        200,
                        "success",
                        None,
                    )?;
                    app.audit.append_in(tx, &fact, true).await?;
                    p.check_live()?;
                    Ok(value.clone())
                })
            },
            TransactionOwner::SoftwareCatalog,
        )
        .await;
    }
    let file = app
        .content
        .as_ref()
        .ok_or(Error::Unsupported)?
        .inspect_upload(input.package_id, &actor(p), &input.package_id.to_string())
        .await?;
    use rss_mdm_agent_wire::runtime::{TaskArchitecture, TaskPlatform};
    let platform = match input.target.platform {
        TaskPlatform::Windows => r::Platform::Windows,
        TaskPlatform::Macos => r::Platform::MacOS,
    };
    let arch = match input.target.architecture {
        TaskArchitecture::X86_64 => r::Architecture::X86_64,
        TaskArchitecture::Aarch64 => r::Architecture::Aarch64,
    };
    if !matches!(
        (file.facts.format, platform),
        (
            r::SoftwareFormat::Exe | r::SoftwareFormat::Msi | r::SoftwareFormat::Msix,
            r::Platform::Windows
        ) | (r::SoftwareFormat::Pkg, r::Platform::MacOS)
    ) {
        return Err(Error::Malformed);
    }
    if !file.facts.architectures.is_empty() && !file.facts.architectures.contains(&arch) {
        return Err(Error::Malformed);
    }
    let version = match (&file.facts.version, &input.version) {
        (Some(observed), Some(submitted)) if observed != submitted => return Err(Error::Malformed),
        (Some(v), _) | (_, Some(v)) => v.clone(),
        _ => return Err(Error::Malformed),
    };
    let now = app
        .clock
        .unix_seconds()
        .ok_or(Error::Unavailable(Failure::Clock))?;
    transaction::run(
        &app.audit,
        &app.runtime,
        app.tenant,
        audit,
        (
            app, p, audit, input, hash, file, version, platform, arch, now,
        ),
        |ctx, tx| {
            Box::pin(async move {
                let (app, p, audit, input, hash, file, version, platform, arch, now) = ctx;
                let snapshot = transaction::current(tx, p).await?;
                snapshot.require(p, Permission::SoftwareWrite, None)?;
                snapshot.require(p, Permission::ResourceWrite, None)?;
                let id = input.package_id.to_string();
                let value = app
                    .catalog
                    .save_installer_in(
                        tx,
                        &app.resources,
                        audit,
                        input.operation_id,
                        hash,
                        &id,
                        &file.artifact,
                        &file.filename,
                        &file.facts,
                        input.behavior.as_ref(),
                        version,
                        *platform,
                        *arch,
                        *now,
                    )
                    .await?;
                p.check_live()?;
                Ok(value)
            })
        },
        TransactionOwner::SoftwareCatalog,
    )
    .await
}
/// Original successful operation only; null remains unknown and grants no replay authority.
pub async fn operation<C: ManagementContentPort>(
    app: &Access<C>,
    p: &AuthorizedPrincipal,
    id: Uuid,
) -> Result<Value, Error> {
    p.require(Permission::SoftwareRead, None)?;
    if p.tenant_id() != app.tenant.to_string() {
        return Err(Error::Forbidden);
    }
    transaction::inspect(&app.runtime, app.tenant, (app, p, id), |ctx, tx| Box::pin(async move {
        let (app, p, id) = *ctx;
        let snapshot = transaction::current(tx, p).await?; snapshot.require(p, Permission::SoftwareRead, None)?;
        let tenant = app.tenant.to_string();
        // Actor is bound into stored request fingerprints; read visibility remains the tenant's software permission.
        Ok(tx.with_connection(move |c| Box::pin(async move { sqlx::query_scalar::<_,Value>("SELECT response FROM mdm_software.operations WHERE tenant_id=$1::uuid AND id=$2")
            .bind(tenant).bind(id).fetch_optional(c).await })).await?.unwrap_or(Value::Null))
    }), TransactionOwner::SoftwareCatalog).await
}
